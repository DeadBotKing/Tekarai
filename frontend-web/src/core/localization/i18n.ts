export const translations: Record<Locale, TranslationMap> = {
  en,
  fa: { ...en, ...fa },
  de: { ...en, ...de },
};

export type TranslationKey = keyof typeof en;

// Persian-pinned translator for the CMMS pages that always render فارسی —
// same pattern as the legacy hard-coded Persian sections (they never react
// to the header language cycle).
export const faText = (
  key: TranslationKey,
  variables: Record<string, string | number> = {},
): string => translate("fa", key, variables);

/**
 * Matches both placeholder dialects that exist in the catalogue: the original
 * `{{name}}` and the far more common `{name}`. They drifted apart because the
 * CMMS phases were written against single braces while the translator only
 * understood double ones, so 23 strings shipped with `{count}` printed
 * verbatim on the maintenance dashboard. One pattern now feeds one
 * substitution pass, and `localization.test.ts` guards the regression.
 */
const PLACEHOLDER_PATTERN = /\{\{(\w+)\}\}|\{(\w+)\}/g;

export const translate = (
  locale: Locale,
  key: TranslationKey,
  variables: Record<string, string | number> = {},
): string => {
  const template = translations[locale][key] ?? translations.en[key] ?? key;
  // A single pass over the template keeps substituted values inert: a value
  // that happens to contain "{name}" is never re-scanned as a placeholder.
  return template.replace(PLACEHOLDER_PATTERN, (match, doubleName?: string, singleName?: string) => {
    const name = doubleName ?? singleName;
    if (name === undefined) return match;
    const value = variables[name];
    // An unknown name keeps its braces so a missing binding stays visible in
    // development instead of silently collapsing to an empty string.
    return value === undefined ? match : String(value);
  });
};
