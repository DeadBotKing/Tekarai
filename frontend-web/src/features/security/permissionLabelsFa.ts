export const permissionLabelFa = (code: string): string => PERMISSION_LABELS_FA[code] ?? "مجوز سفارشی (عنوان فارسی تعریف نشده)";
export const permissionGroupFa = (code: string): string => {
  if (code === "*") return "دسترسی کامل";
  const parts = code.split(".");
  return GROUPS[parts.slice(0, 2).join(".")] ?? GROUPS[parts[0]] ?? "سایر مجوزها";
};
export function groupPermissionsFa(actions: string[], query = ""): Array<{ name: string; actions: string[] }> {
  const normalize = (value: string): string => value.replace(/ي/g, "ی").replace(/ك/g, "ک").replace(/[\u200c\s]+/g, " ").toLocaleLowerCase().trim();
  const needle = normalize(query);
  const result = new Map<string, string[]>();
  for (const code of Array.from(new Set(actions))) {
    const group = permissionGroupFa(code);
    if (needle && !normalize(`${group} ${permissionLabelFa(code)} ${code}`).includes(needle)) continue;
    result.set(group, [...(result.get(group) ?? []), code]);
  }
  return Array.from(result, ([name, codes]) => ({ name, actions: codes.sort((a,b) => permissionLabelFa(a).localeCompare(permissionLabelFa(b), "fa")) })).sort((a,b) => a.name.localeCompare(b.name, "fa"));
}
